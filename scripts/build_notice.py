"""Rewrite the DATA AND SERVICES section of NOTICE from data/attribution.json.

The registry (docs/ATTRIBUTION.md -> data/attribution.json) is authoritative. This keeps the
NOTICE from drifting. The header above DATA AND SERVICES and the SOFTWARE section below are left
as they are.

Usage: python scripts/build_notice.py [--check]
"""

import json
import sys
import textwrap
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
NOTICE = ROOT / "NOTICE"
START = "DATA AND SERVICES\n-----------------\n"
END = "SOFTWARE\n--------\n"
INTRO = (
    "The ids below are the ids used in data/attribution.json, docs/ATTRIBUTION.md and "
    "GET /api/v1/attribution. Usage terms are copied from the registry. Where the registry says "
    '"pending-source", the terms have not yet been read and confirmed, and this NOTICE does not '
    "claim any."
)


def wrap(text: str, indent: int, first: str = "") -> str:
    return textwrap.fill(text, width=79, initial_indent=first, subsequent_indent=" " * indent)


def section() -> str:
    doc = json.loads((ROOT / "data" / "attribution.json").read_text(encoding="utf8"))
    rows = doc if isinstance(doc, list) else doc.get("sources", doc.get("entries", []))
    out = [wrap(INTRO, 0), ""]
    for r in rows:
        pad = 15
        head = f"{r['id']:<{pad}}"
        out.append(wrap(f"{r['name']}. {r['publisher']}.", pad, head))
        out.append(" " * pad + r["url"])
        if r.get("citation") and not r["citation"].startswith("n/a"):
            out.append(wrap(f"Citation: {r['citation']}", pad, " " * pad))
        out.append(wrap(f"Usage statement: {r['usage_statement']}", pad, " " * pad))
        out.append("")
    out.append(
        wrap(
            "The registry (data/attribution.json) is authoritative; this section is "
            "generated by scripts/build_notice.py.",
            0,
        )
    )
    return "\n".join(out) + "\n\n"


def main() -> int:
    text = NOTICE.read_text(encoding="utf8")
    a, b = text.index(START) + len(START), text.index(END)
    new = text[:a] + section() + text[b:]
    if "--check" in sys.argv:
        if new != text:
            print("NOTICE is out of date; run python scripts/build_notice.py")
            return 1
        print("NOTICE is current")
        return 0
    NOTICE.write_text(new, encoding="utf8", newline="\n")
    print("wrote NOTICE")
    return 0


if __name__ == "__main__":
    sys.exit(main())
