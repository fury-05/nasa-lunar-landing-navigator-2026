#!/usr/bin/env python3
"""Regenerate checklist/CHECKLIST.md from todo/PHASE-*.md.
Usage: checklist.py [--check] [--require-complete]"""
import re, sys, pathlib
root = pathlib.Path(__file__).resolve().parent.parent
row = re.compile(r"^\|\s*(P\d-\d\d)\s*\|(.+?)\|\s*(\w+)\s*\|\s*(DONE|PENDING|POSTPONED)\s*\|(.*)\|\s*$")
rows, bad = [], []
for f in sorted((root / "todo").glob("PHASE-*.md")):
    for line in f.read_text(encoding="utf-8").splitlines():
        m = row.match(line)
        if m:
            rows.append((m[1], m[2].strip(), m[3], m[4], m[5].strip()))
        elif line.startswith("| P") and "|" in line:
            bad.append(f"{f.name}: {line[:60]}")
if bad:
    sys.exit("Malformed rows:\n" + "\n".join(bad))
phases = sorted({r[0][:2] for r in rows})
out = ["# Checklist (generated by scripts/checklist.py, do not edit by hand)", "",
       "| Phase | Done | Pending | Postponed | Total |", "|---|---|---|---|---|"]
for p in phases:
    c = [r for r in rows if r[0].startswith(p)]
    out.append(f"| {p} | {sum(r[3]=='DONE' for r in c)} | {sum(r[3]=='PENDING' for r in c)} | {sum(r[3]=='POSTPONED' for r in c)} | {len(c)} |")
out += ["", "| ID | Task | Owner | Status | Evidence / Notes |", "|---|---|---|---|---|"]
out += [f"| {a} | {b} | {c} | {d} | {e} |" for a, b, c, d, e in rows]
text = "\n".join(out) + "\n"
target = root / "checklist" / "CHECKLIST.md"
if "--check" in sys.argv:
    if not target.exists() or target.read_text(encoding="utf-8") != text:
        sys.exit("checklist/CHECKLIST.md is stale: run python scripts/checklist.py")
else:
    target.write_text(text, encoding="utf-8")
if "--require-complete" in sys.argv:
    open_rows = [r[0] for r in rows if r[3] != "DONE"]
    if open_rows:
        sys.exit("Not complete: " + ", ".join(open_rows))
print(f"{len(rows)} rows, {sum(r[3]=='DONE' for r in rows)} done")
